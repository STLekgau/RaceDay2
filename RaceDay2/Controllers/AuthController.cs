

using System;
using System.Collections.Generic;
using System.IdentityModel.Tokens.Jwt;
using System.Security.Claims;
using System.Text;
using Microsoft.AspNetCore.Mvc;
using Microsoft.IdentityModel.Tokens;
using Microsoft.Data.SqlClient;
using Microsoft.Extensions.Configuration;
using RaceDay2.Data;
using RaceDay2.Models;
using RaceDay2.DTOs;

namespace RaceDay2.Controllers
{
    [ApiController]
    [Route("api/auth")]
    public class AuthController : ControllerBase
    {
        private readonly UserRepository _repository;
        private readonly IConfiguration _configuration;

        public AuthController(
            UserRepository repository,
            IConfiguration configuration)
        {
            _repository = repository;
            _configuration = configuration;
        }

        // POST: api/auth/register
        [HttpPost("register")]
        public async Task<IActionResult> Register(RegisterRequest request)
        {
            if (string.IsNullOrWhiteSpace(request.FirstName) ||
                string.IsNullOrWhiteSpace(request.LastName) ||
                string.IsNullOrWhiteSpace(request.Email) ||
                string.IsNullOrWhiteSpace(request.Password))
            {
                return BadRequest(
                    "First name, last name, email and password are required.");
            }

            if (request.Password.Length < 8)
            {
                return BadRequest(
                    "Password must be at least 8 characters long.");
            }

            try
            {
                string email = request.Email.Trim();

                var existingUser =
                    await _repository.GetByEmailAsync(email);

                if (existingUser != null)
                {
                    return Conflict(
                        "An account with this email already exists.");
                }

                var user = new User
                {
                    FirstName = request.FirstName.Trim(),
                    LastName = request.LastName.Trim(),
                    Email = email,

                    // UserRepository hashes this password
                    // before storing it in the database.
                    PasswordHash = request.Password,

                    // Public registration creates participants only.
                    Role = "PARTICIPANT",
                    DateRegistered = DateTime.UtcNow
                };

                int userId = await _repository.CreateAsync(user);

                return Created(
                    $"/api/users/{userId}",
                    new
                    {
                        UserID = userId,
                        Message = "Participant account created successfully."
                    });
            }
            catch (SqlException ex)
            {
                return StatusCode(500, new
                {
                    Message = "A database error occurred during registration.",
                    Detail = ex.Message   // TEMPORARY: remove after debugging
                });
            }
        }

        // POST: api/auth/login
        [HttpPost("login")]
        public async Task<IActionResult> Login(LoginRequest request)
        {
            if (string.IsNullOrWhiteSpace(request.Email) ||
                string.IsNullOrWhiteSpace(request.Password))
            {
                return BadRequest(
                    "Email and password are required.");
            }

            try
            {
                var user = await _repository.GetByEmailAsync(
                    request.Email.Trim());

                if (user == null ||
                    !BCrypt.Net.BCrypt.Verify(
                        request.Password,
                        user.PasswordHash))
                {
                    return Unauthorized(new
                    {
                        Message = "Invalid email or password."
                    });
                }

                string key = _configuration["Jwt:Key"]!;
                string issuer = _configuration["Jwt:Issuer"]!;
                string audience = _configuration["Jwt:Audience"]!;

                // Decode the Base64 secret generated by KeyGenerator.
                byte[] keyBytes = Convert.FromBase64String(key);

                var claims = new List<Claim>
                {
                    new Claim(
                        ClaimTypes.NameIdentifier,
                        user.UserID.ToString()),

                    new Claim(
                        ClaimTypes.Name,
                        user.Email),

                    new Claim(
                        ClaimTypes.Role,
                        user.Role)
                };

                // IMPORTANT: use the decoded key bytes here.
                var signingKey =
                    new SymmetricSecurityKey(keyBytes);

                var credentials = new SigningCredentials(
                    signingKey,
                    SecurityAlgorithms.HmacSha256);

                var token = new JwtSecurityToken(
                    issuer: issuer,
                    audience: audience,
                    claims: claims,
                    expires: DateTime.UtcNow.AddMinutes(60),
                    signingCredentials: credentials);

                string tokenString =
                    new JwtSecurityTokenHandler().WriteToken(token);

                return Ok(new
                {
                    AccessToken = tokenString,
                    TokenType = "Bearer",
                    ExpiresInMinutes = 60,

                    User = new
                    {
                        user.UserID,
                        user.FirstName,
                        user.LastName,
                        user.Email,
                        user.Role
                    }
                });
            }
            catch (SqlException)
            {
                return StatusCode(500, new
                {
                    Message = "Unable to access the user database."
                });
            }
            catch (FormatException)
            {
                return StatusCode(500, new
                {
                    Message = "The JWT secret key is not valid Base64."
                });
            }
        }
    }
}

